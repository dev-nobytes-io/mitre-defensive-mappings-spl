"""Detection strategy layer (ATT&CK x-mitre-detection-strategy -> correlation detections).

In ATT&CK v18+ a detection strategy's analytics are per-platform variants of one plan;
the multi-event chain is described inside each analytic. So correlation happens in two
places, and this module models both:

  content/detection_strategies/DETxxxx.yml   one ATT&CK strategy
      shape: sequence        hand-written SPL implementing the chain the analytic's
                             `gaps` field left out (raw events, joined on a key)
      shape: risk_threshold  parametric search over the Risk data model, scoped to the
                             strategy's analytics (e.g. one source hitting many hosts)
  content/correlations/RISKxxxx.yml          cross-strategy risk correlation
      shape: risk_threshold  scoped to a list of analytics or to all MITRE content

A strategy with implemented analytics but no file is "delegated": its analytics'
own findings and risk events are the strategy's output.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from . import CONTENT_DIR
from .analytics import (CONTENT_TYPES, _conf_sections, _macro_definitions, _macro_index, EXTERNAL_MACROS, AnalyticView,
                        all_views, expand_macros, lint_spl, lookups_used, macros_used)
from .model import AttackModel, DetectionStrategy, Technique
from .scaffold import _Dumper

DET_DIR = CONTENT_DIR / "detection_strategies"
CORR_DIR = CONTENT_DIR / "correlations"
SHAPES = ("sequence", "risk_threshold")
GROUP_BY = ("risk_object", "threat_object")
STATUSES = ("scaffold", "implemented", "reviewed")
RISK_FIELDS = ("risk_score", "risk_events", "distinct_analytics", "distinct_strategies", "distinct_tactics",
               "distinct_techniques", "distinct_risk_objects")

HEADER = "# `attack` is regenerated by `mitremap scaffold`. Edit ONLY `curated`.\n"


@dataclass
class StrategyView:
    """A detection strategy or a cross-strategy correlation, as rendered."""
    id: str                      # DET0363 or RISK0001
    kind: str                    # "strategy" | "correlation"
    curated: dict
    det: DetectionStrategy | None = None
    technique: Technique | None = None
    analytics: list[AnalyticView] = field(default_factory=list)   # implemented analytics of the DET (strategy)
    path: Path | None = None

    @property
    def status(self) -> str:
        return self.curated.get("status") or "scaffold"

    @property
    def implemented(self) -> bool:
        return self.status in ("implemented", "reviewed")

    @property
    def shape(self) -> str:
        return self.curated.get("shape") or "delegated"

    @property
    def title(self) -> str:
        return self.curated.get("title") or (self.det.name if self.det else self.id)

    @property
    def stanza(self) -> str:
        return f"MITRE - {self.id} - {self.title} - Rule"

    @property
    def filter_macro(self) -> str:
        return f"mitre_{self.id.lower()}_filter"

    @property
    def condition_macro(self) -> str:
        return f"mitre_{self.id.lower()}_condition"

    @property
    def content_type(self) -> str:
        # sequences produce a finding and risk like a TTP analytic; risk rules produce a finding only
        return "ttp" if self.shape == "sequence" else "correlation"

    @property
    def url(self) -> str:
        return self.det.url if self.det else ""

    @property
    def scope(self) -> list[str] | str:
        s = self.curated.get("scope")
        if s:
            return s
        return [a.id for a in self.analytics]


# --------------------------------------------------------------------------- load
def _load(p: Path) -> dict:
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {}


def implemented_by_det(m: AttackModel) -> dict[str, list[AnalyticView]]:
    out: dict[str, list[AnalyticView]] = {}
    for v in all_views(m):
        if v.implemented:
            out.setdefault(v.an.det_id, []).append(v)
    return out


def all_strategies(m: AttackModel) -> list[StrategyView]:
    """Every DET with implemented analytics (file or delegated), plus every correlation file."""
    by_det = implemented_by_det(m)
    out: list[StrategyView] = []
    det_ids = set(by_det) | {p.stem for p in DET_DIR.glob("DET*.yml")}
    for det_id in sorted(det_ids):
        det = m.detection_strategies.get(det_id)
        p = DET_DIR / f"{det_id}.yml"
        cur = (_load(p).get("curated") or {}) if p.exists() else {}
        out.append(StrategyView(det_id, "strategy", cur, det, m.techniques.get(det.technique_id) if det else None,
                                by_det.get(det_id, []), p if p.exists() else None))
    for p in sorted(CORR_DIR.glob("RISK*.yml")):
        out.append(StrategyView(p.stem, "correlation", _load(p).get("curated") or {}, path=p))
    return out


def implemented_strategies(m: AttackModel) -> list[StrategyView]:
    return [s for s in all_strategies(m) if s.implemented]


# --------------------------------------------------------------------------- scaffold
def _attack_block(m: AttackModel, det: DetectionStrategy) -> dict:
    te = m.techniques.get(det.technique_id)
    by_det = implemented_by_det(m).get(det.id, [])
    impl = {v.id: v for v in by_det}
    return {
        "url": det.url,
        "name": det.name,
        "attack_release": m.version,
        "technique": {"id": te.id, "name": te.name, "tactics": te.tactics, "usage_score": te.usage_score} if te else None,
        "analytics": [
            {"id": a, "platforms": m.analytics[a].platforms, "implemented": a in impl,
             "content_type": impl[a].content_type if a in impl else None}
            for a in det.analytic_ids if a in m.analytics],
    }


def write_strategy(m: AttackModel, det_id: str, curated: dict | None = None) -> Path:
    p = DET_DIR / f"{det_id}.yml"
    existing = _load(p) if p.exists() else {}
    cur = curated if curated is not None else (existing.get("curated") or {"status": "scaffold", "shape": "sequence", "title": ""})
    doc = {"id": det_id, "attack": _attack_block(m, m.detection_strategies[det_id]), "curated": cur}
    DET_DIR.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER + yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
    return p


def scaffold_strategies(m: AttackModel) -> int:
    n = 0
    for p in sorted(DET_DIR.glob("DET*.yml")):
        if p.stem not in m.detection_strategies:
            print(f"warning: {p.name} is not a detection strategy in ATT&CK v{m.version}; left untouched")
            continue
        write_strategy(m, p.stem)
        n += 1
    return n


def new_strategy(m: AttackModel, det_id: str) -> Path:
    if det_id not in m.detection_strategies:
        raise SystemExit(f"{det_id} is not a detection strategy in ATT&CK v{m.version}")
    if (DET_DIR / f"{det_id}.yml").exists():
        raise SystemExit(f"{DET_DIR / det_id}.yml already exists")
    return write_strategy(m, det_id)


# --------------------------------------------------------------------------- parametric risk search
def risk_scope_clause(s: StrategyView) -> str:
    scope = s.scope
    if scope == "all":
        clause = 'source IN ("MITRE - AN* - Rule", "MITRE - DET* - Rule")'
    else:
        clause = "source IN (" + ", ".join(f'"MITRE - {a} - *"' for a in scope) + ")"
    for key, field in (("risk_object_types", "All_Risk.risk_object_type"), ("threat_object_types", "All_Risk.threat_object_type")):
        vals = s.curated.get(key) or []
        if vals:
            clause += f" {field} IN (" + ", ".join(f'"{v}"' for v in vals) + ")"
    return clause


def risk_threshold_spl(s: StrategyView) -> str:
    """SPL over the Risk data model. Analytic and strategy ids are recovered from the rule name
    (source) and enriched from the TA's ATT&CK lookups, so no custom annotation field paths are needed."""
    c = s.curated
    by_threat = c.get("group_by", "risk_object") == "threat_object"
    dm_by = ("All_Risk.threat_object All_Risk.threat_object_type All_Risk.risk_object All_Risk.risk_object_type source"
             if by_threat else "All_Risk.risk_object All_Risk.risk_object_type source")
    final_by = "threat_object threat_object_type" if by_threat else "risk_object risk_object_type"
    lines = [
        "| tstats `mitre_summariesonly` min(_time) as firstTime max(_time) as lastTime sum(All_Risk.calculated_risk_score) as risk_score count as risk_events",
        f"    from datamodel=Risk.All_Risk where {risk_scope_clause(s)}",
        f"    by {dm_by}",
        "| `drop_dm_object_name(All_Risk)`",
        '| rex field=source "^MITRE - (?<mitre_id>(AN|DET)\\d{4}) - "',
        "| lookup mitre_attack_analytics an_id AS mitre_id OUTPUT det_id AS an_det_id tactics AS an_tactics technique_id AS an_technique_id",
        "| lookup mitre_attack_detection_strategies det_id AS mitre_id OUTPUT tactics AS det_tactics technique_id AS det_technique_id",
        '| eval det_id=coalesce(an_det_id, if(match(mitre_id, "^DET"), mitre_id, null())), tactic=split(coalesce(an_tactics, det_tactics), "|"), technique_id=coalesce(an_technique_id, det_technique_id)',
        "| stats min(firstTime) as firstTime max(lastTime) as lastTime sum(risk_score) as risk_score sum(risk_events) as risk_events"
        " dc(mitre_id) as distinct_analytics dc(det_id) as distinct_strategies dc(tactic) as distinct_tactics dc(technique_id) as distinct_techniques"
        + (" dc(risk_object) as distinct_risk_objects values(risk_object) as risk_object" if by_threat else "")
        + f" values(mitre_id) as mitre_ids values(technique_id) as technique_ids values(tactic) as tactics values(source) as source by {final_by}",
        f"| where `{s.condition_macro}`",
        "| `mitre_ctime(firstTime)` | `mitre_ctime(lastTime)`",
        f"| `{s.filter_macro}`",
    ]
    return "\n".join(lines)


def spl_for(s: StrategyView) -> str:
    return risk_threshold_spl(s) if s.shape == "risk_threshold" else (s.curated.get("spl") or "")


def schedule_for(s: StrategyView) -> dict:
    import zlib
    off = zlib.crc32(s.id.encode()) % 15
    if s.shape == "risk_threshold":
        window = s.curated.get("window", "24h")
        cron = f"{off}-59/15 * * * *" if window in ("15m", "30m", "1h", "60m") else f"{off + 20} * * * *"
        base = {"cron": cron, "earliest": f"-{window}", "latest": "now"}
    else:
        base = {"cron": f"{off}-59/15 * * * *", "earliest": "-75m@m", "latest": "-5m@m"}
    return {**base, **(s.curated.get("schedule") or {})}


def notable_fields(s: StrategyView) -> list[str]:
    if s.shape == "risk_threshold":
        return ["threat_object"] if s.curated.get("group_by") == "threat_object" else ["risk_object"]
    return [o["field"] for o in (s.curated.get("risk") or {}).get("objects") or []]


def strategy_macros(s: StrategyView) -> list[tuple[str, str, str]]:
    out = [(s.filter_macro, "search *", f"Exclusions for {s.id} {s.title}.")]
    if s.shape == "risk_threshold":
        out.append((s.condition_macro, s.curated.get("condition", "distinct_analytics >= 2"),
                    f"Firing condition for {s.id}. Fields: {', '.join(RISK_FIELDS[:6] + (('distinct_risk_objects',) if s.curated.get('group_by') == 'threat_object' else ()))}."))
    prefix = f"mitre_{s.id.lower()}_"
    for t in s.curated.get("tuning") or []:
        name = t.get("name", "")
        if t.get("bind") == "macro" and name.startswith(prefix) and name not in (s.filter_macro, s.condition_macro):
            out.append((name, str(t.get("default", "")), f"{s.id} tunable for '{t.get('element', '')}'." + (f" {t['note']}" if t.get("note") else "")))
    return out


# --------------------------------------------------------------------------- validation
def validate_strategies(m: AttackModel) -> list[str]:
    from . import DIST_DIR
    errs: list[str] = []
    ta = DIST_DIR / "splunk" / "TA-mitre-attack-datacomponents" / "default"
    da = DIST_DIR / "splunk" / "DA-ESS-mitre-attack-detections" / "default"
    macros = _macro_index(_conf_sections(ta / "macros.conf") | _conf_sections(da / "macros.conf"))
    for n, k in EXTERNAL_MACROS.items():
        macros.setdefault(n, set()).add(k)
    macro_defs = _macro_definitions(ta / "macros.conf") | _macro_definitions(da / "macros.conf")
    lookups = _conf_sections(ta / "transforms.conf") | _conf_sections(da / "transforms.conf")
    stanzas = _conf_sections(da / "savedsearches.conf")
    implemented_an = {v.id for v in all_views(m) if v.implemented}

    for s in all_strategies(m):
        if s.path is None:
            continue
        E = lambda msg, s=s: errs.append(f"{s.id}: {msg}")
        c = s.curated
        if s.kind == "strategy" and s.id not in m.detection_strategies:
            E(f"not a detection strategy in ATT&CK v{m.version}"); continue
        if c.get("status") not in STATUSES:
            E(f"status must be one of {STATUSES}")
        if not s.implemented:
            continue
        if c.get("shape") not in SHAPES:
            E(f"shape must be one of {SHAPES}")
            continue
        for req in ("title", "summary"):
            if not (c.get(req) or "").strip():
                E(f"curated.{req} is required")
        if c.get("severity") not in ("informational", "low", "medium", "high", "critical"):
            E("severity must be informational|low|medium|high|critical")
        if s.kind == "correlation" and s.shape != "risk_threshold":
            E("correlations must be shape risk_threshold")
        if s.shape == "risk_threshold":
            if c.get("group_by", "risk_object") not in GROUP_BY:
                E(f"group_by must be one of {GROUP_BY}")
            if c.get("threat_object_types") and c.get("group_by") != "threat_object":
                E("threat_object_types only applies with group_by: threat_object")
            for t in c.get("risk_object_types") or []:
                if t not in ("system", "user", "other"):
                    E(f"risk_object_types: {t} must be system|user|other")
            scope = s.scope
            if scope != "all":
                if not scope:
                    E("scope is empty (no implemented analytics and no curated.scope)")
                for a in scope:
                    if a not in implemented_an and not (a.startswith("DET") and a in {x.id for x in implemented_strategies(m)}):
                        E(f"scope names {a}, which is not an implemented analytic or sequence strategy")
            cond = c.get("condition") or ""
            if not cond.strip():
                E("risk_threshold needs curated.condition")
            names = set(re.findall(r"\b([a-z_]+)\s*[<>=!]", cond))
            if not names or not names <= set(RISK_FIELDS):
                E(f"condition may only use {RISK_FIELDS}; got {sorted(names)}")
            if "distinct_risk_objects" in names and c.get("group_by") != "threat_object":
                E("distinct_risk_objects requires group_by: threat_object")
            if c.get("spl"):
                E("risk_threshold searches are generated; remove curated.spl")
        else:  # sequence
            if s.kind != "strategy":
                E("sequence shape is only for detection strategies")
            spl = c.get("spl") or ""
            if not spl.strip():
                E("sequence needs curated.spl")
            if f"`{s.filter_macro}`" not in spl:
                E(f"spl must apply `{s.filter_macro}`")
            if not re.search(r"`mitre_dc\d{4}", spl):
                E("spl does not use any mitre_dcXXXX data component macro")
            for dc in c.get("data_components") or []:
                if f"mitre_{dc.lower()}" not in spl:
                    E(f"data component {dc} is declared but its macro is not used")
            risk = c.get("risk") or {}
            if not risk.get("objects") or not (risk.get("message") or "").strip():
                E("sequence strategies need risk.objects and risk.message")
            for o in (risk.get("objects") or []) + (risk.get("threat_objects") or []):
                if not re.search(rf"\b{re.escape(o['field'])}\b", spl):
                    E(f"risk field {o['field']} never appears in the SPL")
            for tok in re.findall(r"\$([A-Za-z_][A-Za-z0-9_.]*)\$", risk.get("message") or ""):
                if not re.search(rf"\b{re.escape(tok)}\b", spl):
                    E(f"risk message token ${tok}$ never appears in the SPL")
            if s.analytics and not set(c.get("extends") or []) <= {a.id for a in s.analytics}:
                E("extends names an analytic that is not an implemented analytic of this strategy")
        spl = spl_for(s)
        for e in lint_spl(spl):
            E(f"spl: {e}")
        spl_x = expand_macros(spl, macro_defs)
        for name, n in macros_used(spl):
            if name in (s.filter_macro, s.condition_macro):
                continue
            if name not in macros:
                E(f"unknown macro `{name}`")
            elif n not in macros[name]:
                E(f"macro `{name}` called with {n} argument(s), defined with {sorted(macros[name])}")
        for lk in lookups_used(spl_x):
            if lk not in lookups:
                E(f"unknown lookup {lk}")
        for t in c.get("tuning") or []:
            name = (t.get("name") or "").split("(")[0]
            if t.get("bind") in ("macro", "lookup") and name and name not in spl_x:
                E(f"tuning for {t.get('element')}: {name} is declared but never used")
            if t.get("bind") == "macro" and name.startswith(f"mitre_{s.id.lower()}_") and t.get("default") in (None, ""):
                E(f"tuning for {t.get('element')}: macro {name} needs a default")
        sg = c.get("sigma") or {}
        if not sg:
            E("curated.sigma is required (or sigma.not_expressible with a reason)")
        elif not sg.get("not_expressible") and not (sg.get("rules") and sg.get("correlation")):
            E("curated.sigma needs rules and a correlation, or not_expressible")
        if s.stanza not in stanzas:
            E("detection stanza missing from savedsearches.conf (run make build)")
    return errs
