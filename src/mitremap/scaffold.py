"""Create or refresh content/data_components/DCxxxx.yml.

The `derived` block is regenerated on every run. The `curated` block is yours:
it is preserved verbatim (justification, requirements, overrides, notes).
"""
from __future__ import annotations

import yaml

from . import CONTENT_DIR
from .build import DCView, MAX_CHANNELS_LISTED, build_all, eventtype_search
from .model import AttackModel

DC_DIR = CONTENT_DIR / "data_components"

CURATED_TEMPLATE = {
    "justification": "",
    "requirements": [],
    "overrides": {"feeds": {}, "exclude_feeds": [], "cim": None},
    "notes": [],
}


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper, data):
    if "\n" in data or len(data) > 100:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=">" if len(data) > 100 and "\n" not in data else "|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def derived_block(v: DCView) -> dict:
    srcs = []
    for s in v.sources:
        chans = [c for c, _ in s.channels.most_common(MAX_CHANNELS_LISTED)]
        srcs.append({
            "name": s.canonical,
            "aliases": sorted(n for n in s.raw_names if n != s.canonical) or None,
            "refs": s.refs,
            "platforms": dict(s.platforms.most_common()),
            "feeds": [p.feed for p in s.resolved.providers],
            "parsed": s.parsed or None,
            "unparsed_channels": s.unparsed_channels,
            "channels": chans + ([f"... {len(s.channels) - len(chans)} more"] if len(s.channels) > len(chans) else []),
        })
    feeds = []
    for f in v.feeds:
        feeds.append({
            "feed": f.feed, "have": f.have, "in_scope": f.in_scope,
            "eventtype": f.eventtype if f.in_scope else None,
            "search": eventtype_search(f) if f.in_scope else None,
            "constraint_origin": f.origin,
            "broad_refs": f.broad_refs,
            "sources": f.sources,
            "cim_tags": f.cim_compliant,
        })
    return {
        "platforms": v.platforms,
        "in_scope": v.in_scope,
        "eventtype": v.eventtype,
        "cim": ({"datamodel": v.cim["datamodel"], "dataset": v.cim.get("dataset"), "tags": v.cim.get("tags", [])} if v.cim else None),
        "dependents": {
            "analytics": v.analytics,
            "detection_strategies": len(v.detection_strategies),
            "techniques": len(v.techniques),
            "tactics": dict(v.tactics.most_common()),
        },
        "log_sources": [{k: val for k, val in s.items() if val is not None} for s in srcs],
        "feeds": feeds,
    }


def scaffold(m: AttackModel) -> int:
    DC_DIR.mkdir(parents=True, exist_ok=True)
    n = 0
    for v in build_all(m):
        path = DC_DIR / f"{v.dc.id}.yml"
        existing = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else {}
        curated = (existing or {}).get("curated") or {}
        for k, default in CURATED_TEMPLATE.items():
            curated.setdefault(k, default if not isinstance(default, (dict, list)) else type(default)(default))
        doc = {
            "id": v.dc.id,
            "name": v.dc.name,
            "attack": {
                "url": v.dc.url, "version": v.dc.version, "modified": v.dc.modified[:10],
                "attack_release": m.version, "domains": v.dc.domains,
                "description": v.dc.description,
            },
            "derived": derived_block(v),
            "curated": curated,
            "kql": (existing or {}).get("kql"),
            "esql": (existing or {}).get("esql"),
        }
        text = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110)
        header = (
            "# Generated by `mitremap scaffold`. Edit ONLY the `curated`, `kql` and `esql` blocks;\n"
            "# everything under `derived` is rebuilt from ATT&CK + config on every run.\n"
        )
        path.write_text(header + text, encoding="utf-8")
        n += 1
    return n
