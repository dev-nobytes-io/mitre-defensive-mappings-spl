"""Changelog between two ATT&CK releases for the detection model objects."""
from __future__ import annotations

from pathlib import Path

from . import DOCS_DIR
from .fetch import download, load_slim, slim_path, write_slim
from .model import AttackModel


def _ensure(version: str, domain: str = "enterprise-attack") -> AttackModel:
    if not slim_path(domain, version).exists():
        download(domain, version)
        write_slim(domain, version)
    return AttackModel(load_slim(domain, version), version)


def _delta(old: dict, new: dict, label: str, fmt) -> list[str]:
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    changed = sorted(k for k in set(old) & set(new) if fmt(old[k]) != fmt(new[k]))
    L = [f"### {label}", "", f"Added {len(added)}, removed {len(removed)}, changed {len(changed)}.", ""]
    if added:
        L += ["**Added**", ""] + [f"- {k} {new[k].name}" for k in added] + [""]
    if removed:
        L += ["**Removed**", ""] + [f"- {k} {old[k].name}" for k in removed] + [""]
    if changed:
        L += ["**Changed**", ""] + [f"- {k} {new[k].name}" for k in changed[:200]] + ([f"- … {len(changed) - 200} more"] if len(changed) > 200 else []) + [""]
    return L


def diff(old_v: str, new_v: str) -> Path:
    old, new = _ensure(old_v), _ensure(new_v)
    L = [f"# ATT&CK {old_v} → {new_v}: detection model changes", "",
         "Generated by `mitremap diff`. Objects compared by ATT&CK id; *changed* means the object's name, description, log sources, platforms or references differ.", "",
         "```mermaid", "xychart-beta", f'    title "Object counts {old_v} vs {new_v}"',
         '    x-axis ["Data components", "Analytics", "Detection strategies", "Techniques"]', '    y-axis "count"',
         f"    bar [{len(old.data_components)}, {len(old.analytics)}, {len(old.detection_strategies)}, {len(old.techniques)}]",
         f"    bar [{len(new.data_components)}, {len(new.analytics)}, {len(new.detection_strategies)}, {len(new.techniques)}]", "```", ""]
    L += _delta(old.data_components, new.data_components, "Data components", lambda d: (d.name, d.description, sorted((l.name, l.channel) for l in d.log_sources)))
    L += _delta(old.analytics, new.analytics, "Analytics", lambda a: (a.name, a.description, sorted(a.platforms), sorted((r.name, r.channel, r.dc_id) for r in a.log_source_refs), [(x.get("field"), x.get("description")) for x in a.mutable_elements]))
    L += _delta(old.detection_strategies, new.detection_strategies, "Detection strategies", lambda d: (d.name, sorted(d.analytic_ids), d.technique_id))
    L += _delta(old.techniques, new.techniques, "Techniques", lambda t: (t.name, sorted(t.platforms), sorted(t.tactics)))
    # log source vocabulary
    def vocab(m):
        return {r.name.strip() for dc in m.data_components.values() for r in dc.log_sources} | {r.name.strip() for an in m.analytics.values() for r in an.log_source_refs}
    ov, nv = vocab(old), vocab(new)
    L += ["### Log source names", "", f"New names: {len(nv - ov)}; dropped: {len(ov - nv)}.", ""]
    if nv - ov:
        L += ["**New**", ""] + [f"- `{n}`" for n in sorted(nv - ov)] + [""]
    if ov - nv:
        L += ["**Dropped**", ""] + [f"- `{n}`" for n in sorted(ov - nv)] + [""]
    out = DOCS_DIR / "changelog" / f"attack-{old_v}-to-{new_v}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    return out
