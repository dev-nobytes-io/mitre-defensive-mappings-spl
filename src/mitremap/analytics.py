"""Analytics layer (ATT&CK x-mitre-analytic -> ES detection + Sigma rule).

A YAML file under content/analytics/ exists only for analytics someone has started
implementing. `mitremap new-analytic ANxxxx` scaffolds one; `mitremap scaffold`
refreshes the `attack` and `derived` blocks and preserves `curated`.

Content types (curated.content_type):
    ttp      specific, rarely-benign behaviour      -> notable (+ risk)
    anomaly  noisy alone, meaningful in aggregate   -> risk only
    hunting  pivot material, no decision boundary   -> scheduled search, no action
Baselines are supporting searches attached to an analytic (curated.baselines).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

import yaml

from . import CONTENT_DIR, config
from .build import feed_in_scope, slug
from .logsources import resolve
from .model import Analytic, AttackModel, DetectionStrategy, Technique
from .scaffold import _Dumper

AN_DIR = CONTENT_DIR / "analytics"
CONTENT_TYPES = ("ttp", "anomaly", "hunting")
STATUSES = ("scaffold", "implemented", "reviewed")

CURATED_TEMPLATE: dict = {
    "status": "scaffold",
    "title": "",
    "content_type": None,
    "severity": "medium",
    "summary": "",
    "gaps": "",
    "data_components": [],
    "feeds": [],
    "tuning": [],
    "spl": "",
    "risk": {"message": "", "objects": [], "threat_objects": []},
    "schedule": {},
    "throttle": {},
    "false_positives": [],
    "baselines": [],
    "sigma": {},
}

HEADER = (
    "# `attack` and `derived` are regenerated by `mitremap scaffold` from ATT&CK + config.\n"
    "# Edit ONLY `curated`, `kql` and `esql`.\n"
)


# --------------------------------------------------------------------------- coverage
@lru_cache(maxsize=None)
def _ref_status(name: str) -> str:
    provs = [p for p in resolve(name).providers if not p.virtual]
    if any(p.have for p in provs):
        return "live"
    if any(feed_in_scope(p.feed) for p in provs):
        return "ready"
    return "gap"


def coverage(an: Analytic) -> str:
    """live: every referenced log source has a ticked feed; ready: all in scope; else gap."""
    if not an.log_source_refs:
        return "no-log-source"
    sts = {_ref_status(r.name) for r in an.log_source_refs}
    if sts == {"live"}:
        return "live"
    if sts <= {"live", "ready"}:
        return "ready"
    return "gap"


# --------------------------------------------------------------------------- suggestions
_ANOMALY_WORDS = re.compile(r"\b(unusual|uncommon|anomal\w*|rare|spike|burst|high[- ]volume|high[- ]frequency|excessive|baseline|outside (normal|business)|off[- ]hours|first[- ]seen|never[- ]before)\b", re.I)
_ANOMALY_ELEMENTS = re.compile(r"(threshold|window|entropy|baseline|frequency|count|volume|ratio|rate)", re.I)


def suggest_content_type(an: Analytic, te: Technique | None) -> str:
    """A starting point only; the author decides (curated.content_type)."""
    tactics = set(te.tactics) if te else set()
    if tactics and tactics <= {"discovery", "reconnaissance", "resource-development"}:
        return "hunting"
    hits = len(_ANOMALY_WORDS.findall(an.description)) + sum(1 for me in an.mutable_elements if _ANOMALY_ELEMENTS.search(me.get("field", "")))
    return "anomaly" if hits >= 2 else "ttp"


_TUNING_RULES: list[tuple[re.Pattern, dict]] = [
    (re.compile(r"(time.?window|window|interval|duration)", re.I), {"bind": "macro", "name": "mitre_time_window(1)"}),
    (re.compile(r"(threshold|count|volume|entropy|ratio|rate|frequency|length|size)", re.I), {"bind": "macro", "name": "mitre_{an}_{el}"}),
    (re.compile(r"(user|account|admin|operator|identity)", re.I), {"bind": "lookup", "name": "mitre_account_roles"}),
    (re.compile(r"(parent|process|image|tool|binary|signer|application|apps?$|lolbin)", re.I), {"bind": "lookup", "name": "mitre_allowlist_processes"}),
    (re.compile(r"(path|director|dir|folder|extension|file)", re.I), {"bind": "lookup", "name": "mitre_sensitive_paths"}),
    (re.compile(r"(domain|host|fqdn|url|uri)", re.I), {"bind": "lookup", "name": "mitre_allowlist_domains"}),
    (re.compile(r"(ip|subnet|cidr|destination|source|network|port)", re.I), {"bind": "lookup", "name": "mitre_internal_networks"}),
    (re.compile(r"(regex|pattern|command|string|list|scope)", re.I), {"bind": "macro", "name": "mitre_{an}_{el}"}),
]


def suggest_tuning(an: Analytic) -> list[dict]:
    out = []
    for me in an.mutable_elements:
        el = me.get("field", "")
        binding = {"bind": "filter", "name": f"mitre_{an.id.lower()}_filter"}
        for rx, b in _TUNING_RULES:
            if rx.search(el):
                binding = {k: v.format(an=an.id.lower(), el=slug(el)) for k, v in b.items()}
                break
        out.append({"element": el, **binding})
    return out


# --------------------------------------------------------------------------- views
@dataclass
class AnalyticView:
    an: Analytic
    det: DetectionStrategy | None
    technique: Technique | None
    coverage: str
    suggested_content_type: str
    curated: dict = field(default_factory=dict)
    path: Path | None = None

    @property
    def id(self) -> str:
        return self.an.id

    @property
    def status(self) -> str:
        return (self.curated or {}).get("status") or "none"

    @property
    def implemented(self) -> bool:
        return self.status in ("implemented", "reviewed")

    @property
    def content_type(self) -> str:
        return (self.curated or {}).get("content_type") or self.suggested_content_type

    @property
    def title(self) -> str:
        return (self.curated or {}).get("title") or self.an.name

    @property
    def filter_macro(self) -> str:
        return f"mitre_{self.id.lower()}_filter"

    @property
    def stanza(self) -> str:
        return f"MITRE - {self.id} - {self.title} - Rule"

    @property
    def priority(self) -> int:
        return self.technique.usage_score if self.technique else 0


def analytic_path(an_id: str) -> Path:
    return AN_DIR / f"{an_id}.yml"


def load_curated(an_id: str) -> dict | None:
    p = analytic_path(an_id)
    if not p.exists():
        return None
    return (yaml.safe_load(p.read_text(encoding="utf-8")) or {}).get("curated") or {}


def build_view(m: AttackModel, an: Analytic) -> AnalyticView:
    te = m.technique_for_analytic(an)
    cur = load_curated(an.id)
    return AnalyticView(
        an=an, det=m.detection_strategies.get(an.det_id), technique=te, coverage=coverage(an),
        suggested_content_type=suggest_content_type(an, te), curated=cur or {},
        path=analytic_path(an.id) if cur is not None else None,
    )


def all_views(m: AttackModel) -> list[AnalyticView]:
    return [build_view(m, an) for an in sorted(m.analytics.values(), key=lambda a: a.id)]


def implemented_views(m: AttackModel) -> list[AnalyticView]:
    return [v for v in all_views(m) if v.implemented]


# --------------------------------------------------------------------------- scaffold
def _clean(s):
    if isinstance(s, str):
        # only multi-line text is normalised (so YAML can keep block style); single-line values such as
        # Sigma match strings keep their leading/trailing spaces
        return "\n".join(line.rstrip() for line in s.split("\n")).strip("\n") if "\n" in s else s
    if isinstance(s, list):
        return [_clean(x) for x in s]
    if isinstance(s, dict):
        return {k: _clean(v) for k, v in s.items()}
    return s


def _doc(m: AttackModel, v: AnalyticView, existing: dict) -> dict:
    an, te, det = v.an, v.technique, v.det
    curated = _clean((existing or {}).get("curated") or {})
    for k, default in CURATED_TEMPLATE.items():
        if k not in curated:
            curated[k] = yaml.safe_load(yaml.safe_dump(default)) if isinstance(default, (dict, list)) else default
    ordered = {k: curated[k] for k in CURATED_TEMPLATE} | {k: val for k, val in curated.items() if k not in CURATED_TEMPLATE}
    return {
        "id": an.id,
        "name": an.name,
        "attack": {
            "url": an.url,
            "attack_release": m.version,
            "detection_strategy": {"id": det.id, "name": det.name} if det else None,
            "technique": {"id": te.id, "name": te.name, "tactics": te.tactics, "usage_score": te.usage_score} if te else None,
            "platforms": an.platforms,
            "description": an.description,
            "log_source_references": [
                {"dc": r.dc_id, "dc_name": m.data_components[r.dc_id].name if r.dc_id in m.data_components else "", "name": r.name.strip(), "channel": r.channel}
                for r in an.log_source_refs],
            "mutable_elements": [{"field": me.get("field", ""), "description": me.get("description", "")} for me in an.mutable_elements],
        },
        "derived": {
            "coverage": v.coverage,
            "suggested_content_type": v.suggested_content_type,
            "suggested_tuning": suggest_tuning(an),
        },
        "curated": ordered,
        "kql": (existing or {}).get("kql"),
        "esql": (existing or {}).get("esql"),
    }


def write_analytic(m: AttackModel, an_id: str) -> Path:
    an = m.analytics[an_id]
    p = analytic_path(an_id)
    existing = yaml.safe_load(p.read_text(encoding="utf-8")) if p.exists() else {}
    v = build_view(m, an)
    AN_DIR.mkdir(parents=True, exist_ok=True)
    p.write_text(HEADER + yaml.dump(_doc(m, v, existing), Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8")
    return p


def scaffold_analytics(m: AttackModel) -> int:
    """Refresh every existing analytic file. Files for analytics removed from ATT&CK are reported, not deleted."""
    n = 0
    for p in sorted(AN_DIR.glob("AN*.yml")):
        if p.stem not in m.analytics:
            print(f"warning: {p.name} is not an analytic in ATT&CK v{m.version}; left untouched")
            continue
        write_analytic(m, p.stem)
        n += 1
    return n


def new_analytic(m: AttackModel, an_id: str) -> Path:
    if an_id not in m.analytics:
        raise SystemExit(f"{an_id} is not an analytic in ATT&CK v{m.version}")
    if analytic_path(an_id).exists():
        raise SystemExit(f"{analytic_path(an_id)} already exists")
    return write_analytic(m, an_id)


# --------------------------------------------------------------------------- SPL helpers
EXTERNAL_MACROS = {"drop_dm_object_name": 1}   # Splunk_SA_CIM, shipped with Enterprise Security

_MACRO_RE = re.compile(r"`([A-Za-z0-9_]+)(?:\(([^`]*)\))?`")
_LOOKUP_RE = re.compile(r"\b(?:lookup|inputlookup|outputlookup)\s+(?:(?:append|override_if_empty|create_empty|local|update|max|start)=\S+\s+)*([A-Za-z0-9_]+)")


def flatten_spl(spl: str) -> str:
    return " ".join(line.strip() for line in spl.strip().splitlines() if line.strip())


def macros_used(spl: str) -> list[tuple[str, int]]:
    """(macro name, argument count) for every macro call in the SPL."""
    return [(name, len(args.split(",")) if args.strip() else 0) for name, args in _MACRO_RE.findall(spl)]


def lookups_used(spl: str) -> list[str]:
    return _LOOKUP_RE.findall(spl)


def lint_spl(spl: str) -> list[str]:
    """Syntax-level checks that do not need a Splunk instance."""
    errs = []
    flat = flatten_spl(spl)
    if flat.count("`") % 2:
        errs.append("unbalanced backticks")
    in_q, depth, brackets, prev = False, 0, 0, ""
    for ch in flat:
        if ch == '"' and prev != "\\":
            in_q = not in_q
        elif not in_q:
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "[":
                brackets += 1
            elif ch == "]":
                brackets -= 1
            if depth < 0 or brackets < 0:
                errs.append("closing bracket without opener")
                break
        prev = "" if (ch == "\\" and prev == "\\") else ch
    if in_q:
        errs.append("unbalanced double quotes")
    if depth > 0:
        errs.append("unbalanced parentheses")
    if brackets > 0:
        errs.append("unbalanced square brackets")
    if re.search(r"(?<![A-Za-z_.])index\s*=", flat):
        errs.append("literal index= in SPL; use the mitre_dc*/mitre_idx_* macros")
    if "||" in flat.replace(" ", ""):
        errs.append("empty pipeline stage")
    return errs


# --------------------------------------------------------------------------- validation
def _conf_sections(path: Path) -> set[str]:
    if not path.exists():
        return set()
    return set(re.findall(r"^\[([^\]]+)\]", path.read_text(encoding="utf-8"), re.M))


def _macro_definitions(path: Path) -> dict[str, str]:
    """macro name (without arg count) -> definition text."""
    if not path.exists():
        return {}
    out, cur = {}, None
    for line in path.read_text(encoding="utf-8").splitlines():
        mm = re.match(r"^\[([A-Za-z0-9_]+)(?:\(\d+\))?\]", line)
        if mm:
            cur = mm.group(1)
        elif cur and line.startswith("definition = "):
            out[cur] = line[len("definition = "):]
    return out


def expand_macros(spl: str, defs: dict[str, str], depth: int = 3) -> str:
    """SPL plus the definitions of every macro it calls (transitively), for reference checks."""
    text, seen = spl, set()
    for _ in range(depth):
        new = [defs[n] for n, _ in macros_used(text) if n in defs and n not in seen]
        seen |= {n for n, _ in macros_used(text)}
        if not new:
            break
        text += " " + " ".join(new)
    return text


def _macro_index(sections: set[str]) -> dict[str, set[int]]:
    idx: dict[str, set[int]] = {}
    for sec in sections:
        mm = re.match(r"^([A-Za-z0-9_]+)(?:\((\d+)\))?$", sec)
        if mm:
            idx.setdefault(mm.group(1), set()).add(int(mm.group(2) or 0))
    return idx


def validate_analytics(m: AttackModel) -> list[str]:
    from . import DIST_DIR
    from .build import build_all
    errs: list[str] = []
    ta = DIST_DIR / "splunk" / "TA-mitre-attack-datacomponents" / "default"
    da = DIST_DIR / "splunk" / "DA-ESS-mitre-attack-detections" / "default"
    macros = _macro_index(_conf_sections(ta / "macros.conf") | _conf_sections(da / "macros.conf"))
    for name, n in EXTERNAL_MACROS.items():
        macros.setdefault(name, set()).add(n)
    lookups = _conf_sections(ta / "transforms.conf") | _conf_sections(da / "transforms.conf")
    macro_defs = _macro_definitions(ta / "macros.conf") | _macro_definitions(da / "macros.conf")
    in_scope_dcs = {v.dc.id for v in build_all(m) if v.in_scope}
    stanzas = _conf_sections(da / "savedsearches.conf")

    for p in sorted(AN_DIR.glob("AN*.yml")):
        an_id = p.stem
        if an_id not in m.analytics:
            errs.append(f"{p.name}: not an analytic in ATT&CK v{m.version}")
            continue
        v = build_view(m, m.analytics[an_id])
        c = v.curated
        E = lambda msg: errs.append(f"{an_id}: {msg}")
        if c.get("status") not in STATUSES:
            E(f"status must be one of {STATUSES}")
        if not v.implemented:
            continue
        if c.get("content_type") not in CONTENT_TYPES:
            E(f"content_type must be one of {CONTENT_TYPES}")
        for req in ("title", "summary", "spl"):
            if not (c.get(req) or "").strip():
                E(f"curated.{req} is required for an implemented analytic")
        if c.get("severity") not in ("informational", "low", "medium", "high", "critical"):
            E("severity must be informational|low|medium|high|critical")
        dcs = c.get("data_components") or []
        if not dcs:
            E("curated.data_components is empty")
        for dc in dcs:
            if dc not in in_scope_dcs:
                E(f"data component {dc} has no rendered eventtype")
        spl = c.get("spl") or ""
        spl_x = expand_macros(spl, macro_defs)
        for e in lint_spl(spl):
            E(f"spl: {e}")
        if f"`{v.filter_macro}`" not in spl:
            E(f"spl must apply `{v.filter_macro}`")
        if not re.search(r"`mitre_dc\d{4}", spl):
            E("spl does not use any mitre_dcXXXX data component macro")
        searches = [("spl", spl)] + [(f"baseline {b.get('name')}", b.get("search", "")) for b in c.get("baselines") or []]
        for label, text in searches:
            for name, n in macros_used(text):
                if name not in macros:
                    E(f"{label}: unknown macro `{name}`")
                elif n not in macros[name]:
                    E(f"{label}: macro `{name}` called with {n} argument(s), defined with {sorted(macros[name])}")
            for lk in lookups_used(expand_macros(text, macro_defs)):
                if lk not in lookups:
                    E(f"{label}: unknown lookup {lk}")
        for b in c.get("baselines") or []:
            for e in lint_spl(b.get("search", "")):
                E(f"baseline {b.get('name')}: {e}")
            if not re.search(rf"outputlookup\s+(\S+=\S+\s+)*{re.escape(b.get('lookup', '?'))}\b", b.get("search", "")):
                E(f"baseline {b.get('name')} does not outputlookup {b.get('lookup')}")
            if b.get("lookup") not in spl:
                E(f"spl never reads baseline lookup {b.get('lookup')}")
        risk = c.get("risk") or {}
        if v.content_type in ("ttp", "anomaly"):
            if not risk.get("objects"):
                E("ttp/anomaly analytics need at least one risk object")
            if not (risk.get("message") or "").strip():
                E("risk.message is required")
        for o in (risk.get("objects") or []) + (risk.get("threat_objects") or []):
            if not re.search(rf"\b{re.escape(o['field'])}\b", spl):
                E(f"risk field {o['field']} never appears in the SPL")
            if o in (risk.get("objects") or []) and o.get("type") not in ("system", "user", "other"):
                E(f"risk object type for {o['field']} must be system|user|other")
        for tok in re.findall(r"\$([A-Za-z_][A-Za-z0-9_.]*)\$", risk.get("message") or ""):
            if not re.search(rf"\b{re.escape(tok)}\b", spl):
                E(f"risk message token ${tok}$ never appears in the SPL")
        for t in c.get("tuning") or []:
            if t.get("bind") not in ("macro", "lookup", "filter"):
                E(f"tuning for {t.get('element')}: bind must be macro|lookup|filter")
            name = (t.get("name") or "").split("(")[0]
            if t.get("bind") in ("macro", "filter") and name not in macros and not name.startswith(f"mitre_{an_id.lower()}_"):
                E(f"tuning for {t.get('element')}: unknown macro {name}")
            if t.get("bind") == "lookup" and name not in lookups:
                E(f"tuning for {t.get('element')}: unknown lookup {name}")
            if t.get("bind") in ("macro", "lookup") and name and name not in spl_x and not any(name in (b.get("search") or "") for b in c.get("baselines") or []):
                E(f"tuning for {t.get('element')}: {name} is declared but never used in the SPL")
            if t.get("bind") == "macro" and name.startswith(f"mitre_{an_id.lower()}_") and t.get("default") in (None, ""):
                E(f"tuning for {t.get('element')}: analytic macro {name} needs a default")
        sg = c.get("sigma") or {}
        if not sg:
            E("curated.sigma is required (use sigma.not_expressible with a reason if Sigma cannot express it)")
        elif not sg.get("not_expressible") and not (sg.get("detection") or sg.get("rules")):
            E("curated.sigma needs detection or rules")
        if v.stanza not in stanzas:
            E("detection stanza missing from savedsearches.conf (run make build)")
    return errs
