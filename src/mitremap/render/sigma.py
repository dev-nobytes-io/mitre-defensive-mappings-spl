"""Render Sigma logsource mapping and a pySigma processing pipeline.

The pipeline maps Sigma logsources to this repo's eventtypes, indexes and sourcetypes
(or sources, for the Windows event log feeds) so a Sigma rule converted with
pysigma-backend-splunk is scoped by the matching ATT&CK data component. Chain it after
the sysmon pipeline only; splunk_windows would add a conflicting classic source.
"""
from __future__ import annotations

from pathlib import Path

import yaml

from .. import DIST_DIR, config
from ..build import DCView
from ..model import AttackModel


class SigmaRenderer:
    name = "sigma"

    def render(self, m: AttackModel, views: list[DCView]) -> list[Path]:
        root = DIST_DIR / "sigma"
        (root / "pipelines").mkdir(parents=True, exist_ok=True)
        by_name = {v.dc.name: v for v in views}
        sig = config.sigma()
        products = sig["products"]

        # ---- logsource map: DC -> sigma logsources (per feed)
        ls_map = {}
        for v in views:
            if not v.in_scope:
                continue
            entries = []
            for f in [f for f in v.feeds if f.in_scope]:
                product = products.get(f.feed)
                if not product:
                    continue
                cats = [c for c, per in sig["categories"].items() if v.dc.name in (per.get(product) or [])]
                svc = sorted({s.resolved.sigma.get("service") for s in v.sources if s.resolved.sigma.get("product") == product and s.resolved.sigma.get("service")})
                entries.append({"feed": f.feed, "eventtype": f.eventtype, "product": product, "categories": cats or None, "services": svc or None})
            ls_map[v.dc.id] = {"name": v.dc.name, "umbrella_eventtype": v.eventtype, "logsources": [{k: val for k, val in e.items() if val} for e in entries]}
        p1 = root / "logsources.yml"
        p1.write_text("# Generated by mitremap: ATT&CK data component -> Sigma logsource(s) and the Splunk eventtypes that scope them.\n"
                      + yaml.safe_dump(ls_map, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")

        # ---- pySigma pipeline
        transformations = []
        for cat, per in sig["categories"].items():
            for product, dc_names in per.items():
                # feed-specific eventtypes whose feed maps to this Sigma product; fall back to the umbrella
                ets = []
                for n in dc_names:
                    v = by_name.get(n)
                    if not v or not v.in_scope:
                        continue
                    per_feed = [f.eventtype for f in v.feeds if f.in_scope and products.get(f.feed) == product]
                    ets += per_feed or [v.eventtype]
                if not ets:
                    continue
                transformations.append({
                    "id": f"dc_{product}_{cat}",
                    "type": "add_condition",
                    "conditions": {"eventtype": ets if len(ets) > 1 else ets[0]},
                    "rule_conditions": [{"type": "logsource", "product": product, "category": cat}],
                })
        # templated feeds (Corelight, Palo Alto, ESXi): product + service=<log> -> exact sourcetype
        seen = set()
        for feed, f in config.stack().items():
            tmpl, product = f.get("sourcetype_template"), products.get(feed)
            if not tmpl or "{log}" not in tmpl or not product or f.get("render") is False:
                continue
            for log in f.get("default_logs", []):
                key = (product, log)
                if key in seen:
                    continue
                seen.add(key)
                transformations.append({
                    "id": f"svc_{product}_{log}",
                    "type": "add_condition",
                    "conditions": {"index": f["index"], "sourcetype": tmpl.format(log=log)},
                    "rule_conditions": [{"type": "logsource", "product": product, "service": log}],
                })
        # service-level logsources -> index + sourcetype from the feed config
        for name, spec in config.log_sources()["sources"].items():
            sg = spec.get("sigma") or {}
            if not sg.get("service") or sg.get("product") in (None, "none"):
                continue
            prov = next((p for p in spec.get("providers") or [] if products.get(p.get("feed")) == sg["product"]), (spec.get("providers") or [{}])[0])
            feed = prov.get("feed")
            if not feed or feed not in config.stack() or config.feed(feed).get("virtual") or config.feed(feed).get("render") is False:
                continue
            key = (sg["product"], sg["service"])
            if key in seen:
                continue
            seen.add(key)
            f = config.feed(feed)
            from ..logsources import sourcetypes_for, Provider
            sts = sourcetypes_for(Provider(**prov), {})
            cond = {}
            if f.get("index"):
                cond["index"] = f["index"]
            if sts:
                cond[f.get("constraint_field", "sourcetype")] = sts if len(sts) > 1 else sts[0]
            if not cond:
                continue
            transformations.append({
                "id": f"svc_{sg['product']}_{sg['service']}".replace("-", "_").replace("/", "_"),
                "type": "add_condition",
                "conditions": cond,
                "rule_conditions": [{"type": "logsource", "product": sg["product"], "service": sg["service"]}],
            })
        # Splunk_TA_windows exposes the event id as EventCode; Sigma rules use EventID
        transformations.append({
            "id": "windows_eventid_to_eventcode",
            "type": "field_name_mapping",
            "mapping": {"EventID": "EventCode"},
            "rule_conditions": [{"type": "logsource", "product": "windows"}],
        })
        pipeline = {
            "name": f"MITRE ATT&CK v{m.version} data components -> Splunk eventtypes",
            "priority": 30,
            "vars": {"attack_version": m.version},
            "transformations": transformations,
        }
        p2 = root / "pipelines" / "splunk_mitre_dc.yml"
        p2.write_text("# Generated by mitremap. Use: sigma convert -t splunk -p sysmon -p dist/sigma/pipelines/splunk_mitre_dc.yml rule.yml\n# Do not add -p splunk_windows: it adds source='WinEventLog:<channel>' (classic rendering), which contradicts the XML source set here.\n"
                      + yaml.safe_dump(pipeline, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
        return [p1, p2] + self._rules(m, root)

    # ------------------------------------------------------------------ rules for implemented analytics
    def _rules(self, m: AttackModel, root: Path) -> list[Path]:
        import uuid
        from ..analytics import implemented_views
        from ..build import slug
        from ..fetch import load_manifest
        rules_dir = root / "rules"
        rules_dir.mkdir(parents=True, exist_ok=True)
        date = load_manifest().get("released", "")
        keep, out = set(), []
        for v in implemented_views(m):
            sg = v.curated.get("sigma") or {}
            if not sg or sg.get("not_expressible"):
                continue
            te = v.technique
            tags = [f"attack.{t}" for t in (te.tactics if te else [])] + ([f"attack.{te.id.lower()}"] if te else [])
            common = {
                "status": "experimental",
                "description": (v.curated.get("summary") or "").strip(),
                "references": [v.an.url] + ([te.url] if te else []),
                "author": "mitremap",
                "date": date,
                "tags": tags,
            }
            custom = {"mitre_analytic": v.id, "mitre_detection_strategy": v.det.id if v.det else "", "mitre_data_components": list(v.curated.get("data_components") or [])}
            base_rules = sg.get("rules") or [{k: sg[k] for k in ("logsource", "detection") if k in sg}]
            docs = []
            for i, r in enumerate(base_rules):
                name = r.get("name") or f"{v.id.lower()}_{i}"
                title = r.get("title") or (v.title if len(base_rules) == 1 else f"{v.title} ({name})")
                d = {"title": title, "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{v.an.url}#{name}")), "name": name, **common,
                     "logsource": r["logsource"], "detection": r["detection"],
                     "falsepositives": sg.get("falsepositives") or v.curated.get("false_positives") or ["Unknown"],
                     "level": r.get("level") or (sg.get("level") or v.curated.get("severity", "medium")) if not sg.get("correlation") else "informational",
                     **custom}
                docs.append(d)
            if sg.get("correlation"):
                corr = dict(sg["correlation"])
                corr.setdefault("rules", [d["name"] for d in docs])
                docs.append({"title": v.title, "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"{v.an.url}#correlation")), **common,
                             "correlation": corr, "falsepositives": sg.get("falsepositives") or v.curated.get("false_positives") or ["Unknown"],
                             "level": sg.get("level") or v.curated.get("severity", "medium"), **custom})
            p = rules_dir / f"{v.id.lower()}_{slug(v.title)[:60]}.yml"
            text = "# Generated by mitremap from content/analytics/" + v.id + ".yml\n" + "---\n".join(
                yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=120) for d in docs)
            p.write_text(text, encoding="utf-8")
            keep.add(p.name)
            out.append(p)
        from ..strategies import implemented_strategies
        for sv in implemented_strategies(m):
            sg = sv.curated.get("sigma") or {}
            if not sg or sg.get("not_expressible"):
                continue
            te = sv.technique
            tags = ([f"attack.{t}" for t in te.tactics] + [f"attack.{te.id.lower()}"]) if te else []
            common = {"status": "experimental", "description": (sv.curated.get("summary") or "").strip(),
                      "references": [sv.url] if sv.url else [], "author": "mitremap", "date": date, "tags": tags}
            custom = {"mitre_detection_strategy": sv.id, "mitre_data_components": list(sv.curated.get("data_components") or [])}
            docs = []
            for r in sg["rules"]:
                docs.append({"title": r.get("title") or f"{sv.title} ({r['name']})", "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"mitremap:{sv.id}#{r['name']}")),
                             "name": r["name"], **common, "logsource": r["logsource"], "detection": r["detection"],
                             "falsepositives": sg.get("falsepositives") or sv.curated.get("false_positives") or ["Unknown"],
                             "level": "informational", **custom})
            corr = dict(sg["correlation"])
            corr.setdefault("rules", [d["name"] for d in docs])
            docs.append({"title": sv.title, "id": str(uuid.uuid5(uuid.NAMESPACE_URL, f"mitremap:{sv.id}#correlation")), **common,
                         "correlation": corr, "falsepositives": sg.get("falsepositives") or sv.curated.get("false_positives") or ["Unknown"],
                         "level": sv.curated.get("severity", "high"), **custom})
            p = rules_dir / f"{sv.id.lower()}_{slug(sv.title)[:60]}.yml"
            p.write_text(f"# Generated by mitremap from content/{'detection_strategies' if sv.kind == 'strategy' else 'correlations'}/{sv.id}.yml\n"
                         + "---\n".join(yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=120) for d in docs), encoding="utf-8")
            keep.add(p.name)
            out.append(p)
        for stale in rules_dir.glob("*.yml"):
            if stale.name not in keep:
                stale.unlink()
        return out
