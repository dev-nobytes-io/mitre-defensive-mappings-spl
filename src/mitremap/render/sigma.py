"""Render Sigma logsource mapping and a pySigma processing pipeline.

The pipeline maps Sigma logsources to this repo's eventtypes/sourcetypes so a Sigma
rule converted with pysigma-backend-splunk is scoped by the matching ATT&CK data
component. Chain it after a field-mapping pipeline (e.g. sysmon + splunk_windows).
"""
from __future__ import annotations

from pathlib import Path

import yaml

from .. import DIST_DIR, config
from ..build import DCView
from ..model import AttackModel


class SigmaRenderer:
    name = "sigma"

    def render(self, m: AttackModel, views: list[DCView]) -> list[Path]:
        root = DIST_DIR / "sigma"
        (root / "pipelines").mkdir(parents=True, exist_ok=True)
        by_name = {v.dc.name: v for v in views}
        sig = config.sigma()
        products = sig["products"]

        # ---- logsource map: DC -> sigma logsources (per feed)
        ls_map = {}
        for v in views:
            if not v.in_scope:
                continue
            entries = []
            for f in [f for f in v.feeds if f.in_scope]:
                product = products.get(f.feed)
                if not product:
                    continue
                cats = [c for c, per in sig["categories"].items() if v.dc.name in (per.get(product) or [])]
                svc = sorted({s.resolved.sigma.get("service") for s in v.sources if s.resolved.sigma.get("product") == product and s.resolved.sigma.get("service")})
                entries.append({"feed": f.feed, "eventtype": f.eventtype, "product": product, "categories": cats or None, "services": svc or None})
            ls_map[v.dc.id] = {"name": v.dc.name, "umbrella_eventtype": v.eventtype, "logsources": [{k: val for k, val in e.items() if val} for e in entries]}
        p1 = root / "logsources.yml"
        p1.write_text("# Generated by mitremap: ATT&CK data component -> Sigma logsource(s) and the Splunk eventtypes that scope them.\n"
                      + yaml.safe_dump(ls_map, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")

        # ---- pySigma pipeline
        transformations = []
        for cat, per in sig["categories"].items():
            for product, dc_names in per.items():
                # feed-specific eventtypes whose feed maps to this Sigma product; fall back to the umbrella
                ets = []
                for n in dc_names:
                    v = by_name.get(n)
                    if not v or not v.in_scope:
                        continue
                    per_feed = [f.eventtype for f in v.feeds if f.in_scope and products.get(f.feed) == product]
                    ets += per_feed or [v.eventtype]
                if not ets:
                    continue
                transformations.append({
                    "id": f"dc_{product}_{cat}",
                    "type": "add_condition",
                    "conditions": {"eventtype": ets if len(ets) > 1 else ets[0]},
                    "rule_conditions": [{"type": "logsource", "product": product, "category": cat}],
                })
        # service-level logsources -> index + sourcetype from the feed config
        seen = set()
        for name, spec in config.log_sources()["sources"].items():
            sg = spec.get("sigma") or {}
            if not sg.get("service") or sg.get("product") in (None, "none"):
                continue
            prov = (spec.get("providers") or [{}])[0]
            feed = prov.get("feed")
            if not feed or feed not in config.stack() or config.feed(feed).get("virtual") or config.feed(feed).get("render") is False:
                continue
            key = (sg["product"], sg["service"])
            if key in seen:
                continue
            seen.add(key)
            f = config.feed(feed)
            from ..logsources import sourcetypes_for, Provider
            sts = sourcetypes_for(Provider(**prov), {})
            cond = {}
            if f.get("index"):
                cond["index"] = f["index"]
            if sts:
                cond["sourcetype"] = sts if len(sts) > 1 else sts[0]
            if not cond:
                continue
            transformations.append({
                "id": f"svc_{sg['product']}_{sg['service']}".replace("-", "_").replace("/", "_"),
                "type": "add_condition",
                "conditions": cond,
                "rule_conditions": [{"type": "logsource", "product": sg["product"], "service": sg["service"]}],
            })
        pipeline = {
            "name": f"MITRE ATT&CK v{m.version} data components -> Splunk eventtypes",
            "priority": 30,
            "vars": {"attack_version": m.version},
            "transformations": transformations,
        }
        p2 = root / "pipelines" / "splunk_mitre_dc.yml"
        p2.write_text("# Generated by mitremap. Use: sigma convert -t splunk -p sysmon -p splunk_windows -p dist/sigma/pipelines/splunk_mitre_dc.yml rule.yml\n"
                      + yaml.safe_dump(pipeline, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
        return [p1, p2]
