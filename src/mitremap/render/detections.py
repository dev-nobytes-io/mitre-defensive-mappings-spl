"""Render implemented analytics as Splunk Enterprise Security 8 detections.

Output app: dist/splunk/DA-ESS-mitre-attack-detections
    savedsearches.conf   one stanza per implemented analytic (+ attached baselines)
    macros.conf          per-analytic filter macro and analytic-specific tunables
    transforms.conf      lookups produced by baselines
Stanza shape follows Splunk's contentctl output for ES 8 (event-based detections).
Everything ships disabled; the content type decides the adaptive response:
    ttp -> notable + risk, anomaly -> risk only, hunting -> no action.
"""
from __future__ import annotations

import csv
import json
import zlib
from pathlib import Path

from .. import DIST_DIR
from ..analytics import AnalyticView, flatten_spl, implemented_views
from ..build import DCView
from ..model import AttackModel

APP = "DA-ESS-mitre-attack-detections"

_NETWORK_DCS = {"DC0078", "DC0082", "DC0085", "DC0102", "DC0104", "DC0106", "DC0051", "DC0043"}
_ACCESS_DCS = {"DC0002", "DC0067", "DC0088", "DC0084"}


def security_domain(v: AnalyticView) -> str:
    dcs = set(v.curated.get("data_components") or [])
    if dcs and dcs <= _NETWORK_DCS:
        return "network"
    if dcs and dcs <= _ACCESS_DCS:
        return "access"
    return "endpoint"


def default_schedule(v: AnalyticView) -> dict:
    """Every 15 minutes with a per-analytic minute offset so searches do not start together."""
    off = zlib.crc32(v.id.encode()) % 15
    return {"cron": f"{off}-59/15 * * * *", "earliest": "-20m@m", "latest": "-5m@m"}


def schedule(v: AnalyticView) -> dict:
    return {**default_schedule(v), **(v.curated.get("schedule") or {})}


def annotations(m: AttackModel, v: AnalyticView) -> dict:
    return {
        "mitre_attack": [v.technique.id] if v.technique else [],
        "mitre_det": [v.det.id] if v.det else [],
        "mitre_an": [v.id],
        "mitre_dc": list(v.curated.get("data_components") or []),
        "attack_version": [m.version],
    }


def risk_param(v: AnalyticView) -> list[dict]:
    r = v.curated.get("risk") or {}
    out = [{"risk_object_field": o["field"], "risk_object_type": o.get("type", "system"), "risk_score": int(o.get("score", 20))} for o in r.get("objects") or []]
    out += [{"threat_object_field": t["field"], "threat_object_type": t.get("type", t["field"])} for t in r.get("threat_objects") or []]
    return out


def tunable_macros(v: AnalyticView) -> list[tuple[str, str, str]]:
    """(stanza, definition, description) for macros owned by this analytic."""
    out = [(v.filter_macro, "search *", f"Exclusions for {v.id} {v.title}. Example: search NOT (dest=scanner01 OR user=svc_backup)")]
    prefix = f"mitre_{v.id.lower()}_"
    for t in v.curated.get("tuning") or []:
        name = t.get("name", "")
        if t.get("bind") == "macro" and name.startswith(prefix) and name != v.filter_macro:
            desc = f"{v.id} tunable for ATT&CK mutable element '{t.get('element', '')}'." + (f" {t['note']}" if t.get("note") else "")
            out.append((name, str(t.get("default", "")), desc))
    return out


class DetectionsRenderer:
    name = "detections"

    def render(self, m: AttackModel, views: list[DCView]) -> list[Path]:
        root = DIST_DIR / "splunk" / APP
        default, lookups, meta = root / "default", root / "lookups", root / "metadata"
        for d in (default, lookups, meta):
            d.mkdir(parents=True, exist_ok=True)
        avs = implemented_views(m)
        from ..strategies import implemented_strategies
        svs = implemented_strategies(m)
        out = [
            self._savedsearches(default / "savedsearches.conf", m, avs, svs),
            self._macros(default / "macros.conf", avs, svs),
            self._transforms(default / "transforms.conf", lookups, avs),
            self._app_conf(default / "app.conf", m),
            self._readme(root / "README.md", m, avs, svs),
        ]
        (meta / "default.meta").write_text("[]\naccess = read : [ * ], write : [ admin, sc_admin, ess_admin ]\nexport = system\n", encoding="utf-8")
        out.append(meta / "default.meta")
        return out

    # ------------------------------------------------------------------ savedsearches
    def _savedsearches(self, path: Path, m: AttackModel, avs: list[AnalyticView], svs: list) -> Path:
        L = [f"# Generated by mitremap from ATT&CK v{m.version}. Do not edit; override in local/savedsearches.conf.",
             "# One detection per implemented ATT&CK analytic. All ship disabled.", ""]
        for v in avs:
            c = v.curated
            ctype = v.content_type
            sch = schedule(v)
            te = v.technique
            desc = f"{c.get('summary', '').strip()} ATT&CK {v.id} / {v.det.id if v.det else ''} / {te.id if te else ''} {te.name if te else ''}. Content type: {ctype}."
            L.append(f"[{v.stanza}]")
            L.append(f"description = {desc}")
            L.append("action.correlationsearch.enabled = 1")
            L.append("action.correlationsearch.detection_type = ebd")
            L.append(f"action.correlationsearch.label = {v.stanza}")
            L.append("action.correlationsearch.annotations = " + json.dumps(annotations(m, v)))
            L.append("action.correlationsearch.metadata = " + json.dumps({"content_type": ctype, "analytic_url": v.an.url, "attack_version": m.version}))
            risk = risk_param(v)
            if ctype in ("ttp", "anomaly") and risk:
                L.append("action.risk = 1")
                L.append("action.risk.param._risk_message = " + (c.get("risk") or {}).get("message", v.title))
                L.append("action.risk.param._risk = " + json.dumps(risk))
                L.append("action.risk.param._risk_score = 0")
                L.append("action.risk.param.verbose = 0")
            if ctype == "ttp":
                nes = ",".join(o["field"] for o in (c.get("risk") or {}).get("objects") or [])
                L.append("action.notable = 1")
                L.append('action.notable.param._entities = [{"risk_object_field": "N/A", "risk_object_type": "N/A", "risk_score": 0}]')
                L.append(f"action.notable.param.nes_fields = {nes}")
                L.append(f"action.notable.param.rule_description = {c.get('summary', '').strip()}")
                L.append(f"action.notable.param.rule_title = {(c.get('risk') or {}).get('message') or v.title}")
                L.append(f"action.notable.param.security_domain = {security_domain(v)}")
                L.append(f"action.notable.param.severity = {c.get('severity', 'medium')}")
            L.append(f"cron_schedule = {sch['cron']}")
            L.append(f"dispatch.earliest_time = {sch['earliest']}")
            L.append(f"dispatch.latest_time = {sch['latest']}")
            L.append("schedule_window = auto")
            L.append("alert.digest_mode = 1")
            L.append("disabled = true")
            L.append("enableSched = 1")
            L.append("allow_skew = 100%")
            L.append("counttype = number of events")
            L.append("relation = greater than")
            L.append("quantity = 0")
            L.append("realtime_schedule = 0")
            L.append("is_visible = false")
            th = c.get("throttle") or {}
            if th.get("fields") and ctype != "hunting":
                L.append("alert.suppress = true")
                L.append("alert.suppress.fields = " + ",".join(th["fields"]))
                L.append(f"alert.suppress.period = {th.get('period', '3600s')}")
            L.append("search = " + flatten_spl(c["spl"]))
            L.append("")
            for b in c.get("baselines") or []:
                L.append(f"[MITRE - {v.id} - Baseline - {b['name']}]")
                L.append(f"description = Baseline for {v.id} {v.title}: {b.get('description', '').strip()} Writes lookup {b['lookup']}.")
                L.append(f"cron_schedule = {b.get('cron', '17 3 * * *')}")
                L.append(f"dispatch.earliest_time = {b.get('earliest', '-30d@d')}")
                L.append(f"dispatch.latest_time = {b.get('latest', '-1h@h')}")
                L.append("schedule_window = auto")
                L.append("disabled = true")
                L.append("enableSched = 1")
                L.append("realtime_schedule = 0")
                L.append("is_visible = false")
                L.append("search = " + flatten_spl(b["search"]))
                L.append("")
        L += self._strategy_stanzas(m, svs)
        L += self._health_stanzas(m)
        path.write_text("\n".join(L), encoding="utf-8")
        return path

    def _health_stanzas(self, m: AttackModel) -> list[str]:
        from ..health import rules, support_searches
        L = ["", "# ---- supporting searches (no alert action; they maintain lookups)", ""]
        for sp in support_searches():
            L += [f"[MITRE - {sp.id} - {sp.title}]", f"description = {sp.summary}",
                  f"cron_schedule = {sp.cron}", f"dispatch.earliest_time = {sp.earliest}", "dispatch.latest_time = now",
                  "schedule_window = auto", "disabled = true", "enableSched = 1", "realtime_schedule = 0", "is_visible = false",
                  "search = " + flatten_spl(sp.spl), ""]
        L += ["", "# ---- telemetry health (generated from config/stack.yml)", ""]
        for r in rules():
            stanza = f"MITRE - {r.id} - {r.title} - Rule"
            ann = {"mitre_attack": [r.technique] if r.technique else [], "mitre_dc": ["DC0018"], "attack_version": [m.version]}
            L += [f"[{stanza}]", f"description = {r.summary}",
                  "action.correlationsearch.enabled = 1", "action.correlationsearch.detection_type = ebd",
                  f"action.correlationsearch.label = {stanza}",
                  "action.correlationsearch.annotations = " + json.dumps(ann),
                  "action.correlationsearch.metadata = " + json.dumps({"content_type": "health", "attack_version": m.version})]
            if r.risk:
                L += ["action.risk = 1", f"action.risk.param._risk_message = {r.risk['message']}",
                      "action.risk.param._risk = " + json.dumps([{"risk_object_field": o["field"], "risk_object_type": o["type"], "risk_score": o["score"]} for o in r.risk["objects"]]),
                      "action.risk.param._risk_score = 0", "action.risk.param.verbose = 0"]
            L += ["action.notable = 1",
                  'action.notable.param._entities = [{"risk_object_field": "N/A", "risk_object_type": "N/A", "risk_score": 0}]',
                  "action.notable.param.nes_fields = " + ",".join(r.notable_fields),
                  f"action.notable.param.rule_description = {r.summary}",
                  f"action.notable.param.rule_title = {r.title}",
                  "action.notable.param.security_domain = endpoint" if r.risk else "action.notable.param.security_domain = audit",
                  f"action.notable.param.severity = {r.severity}",
                  f"cron_schedule = {r.cron}", f"dispatch.earliest_time = {r.earliest}", "dispatch.latest_time = now",
                  "schedule_window = auto", "alert.digest_mode = 1", "disabled = true", "enableSched = 1", "allow_skew = 100%",
                  "counttype = number of events", "relation = greater than", "quantity = 0", "realtime_schedule = 0", "is_visible = false",
                  "alert.suppress = true", "alert.suppress.fields = " + ",".join(r.notable_fields), "alert.suppress.period = 86400s",
                  "search = " + flatten_spl(r.spl), ""]
        return L

    def _strategy_stanzas(self, m: AttackModel, svs: list) -> list[str]:
        from ..strategies import notable_fields, schedule_for, spl_for
        L = ["", "# ---- detection strategies (ATT&CK DET) and cross-strategy risk correlations", ""]
        for s in svs:
            c = s.curated
            te = s.technique
            sch = schedule_for(s)
            scope = s.scope if s.scope != "all" else []
            ann = {
                "mitre_attack": [te.id] if te else [],
                "mitre_det": [s.id] if s.kind == "strategy" else [],
                "mitre_an": list(c.get("extends") or ([] if s.shape == "sequence" else [a for a in scope if a.startswith("AN")])),
                "mitre_dc": list(c.get("data_components") or []),
                "attack_version": [m.version],
            }
            ref = f"ATT&CK {s.id} / {te.id} {te.name}" if te else s.id
            L.append(f"[{s.stanza}]")
            L.append(f"description = {c.get('summary', '').strip()} {ref}. Shape: {s.shape}.")
            L.append("action.correlationsearch.enabled = 1")
            L.append("action.correlationsearch.detection_type = ebd")
            L.append(f"action.correlationsearch.label = {s.stanza}")
            L.append("action.correlationsearch.annotations = " + json.dumps(ann))
            L.append("action.correlationsearch.metadata = " + json.dumps({"content_type": s.content_type, "shape": s.shape, "strategy_url": s.url, "attack_version": m.version}))
            if s.shape == "sequence":
                r = c.get("risk") or {}
                risk = [{"risk_object_field": o["field"], "risk_object_type": o.get("type", "system"), "risk_score": int(o.get("score", 50))} for o in r.get("objects") or []]
                risk += [{"threat_object_field": t["field"], "threat_object_type": t.get("type", t["field"])} for t in r.get("threat_objects") or []]
                L.append("action.risk = 1")
                L.append("action.risk.param._risk_message = " + r.get("message", s.title))
                L.append("action.risk.param._risk = " + json.dumps(risk))
                L.append("action.risk.param._risk_score = 0")
                L.append("action.risk.param.verbose = 0")
                title = r.get("message") or s.title
            else:
                title = "RBA: " + (c.get("finding_title") or s.title)
            L.append("action.notable = 1")
            L.append('action.notable.param._entities = [{"risk_object_field": "N/A", "risk_object_type": "N/A", "risk_score": 0}]')
            L.append("action.notable.param.nes_fields = " + ",".join(notable_fields(s)))
            L.append(f"action.notable.param.rule_description = {c.get('summary', '').strip()}")
            L.append(f"action.notable.param.rule_title = {title}")
            L.append(f"action.notable.param.security_domain = {c.get('security_domain', 'threat')}")
            L.append(f"action.notable.param.severity = {c.get('severity', 'high')}")
            L.append(f"cron_schedule = {sch['cron']}")
            L.append(f"dispatch.earliest_time = {sch['earliest']}")
            L.append(f"dispatch.latest_time = {sch['latest']}")
            L.append("schedule_window = auto")
            L.append("alert.digest_mode = 1")
            L.append("disabled = true")
            L.append("enableSched = 1")
            L.append("allow_skew = 100%")
            L.append("counttype = number of events")
            L.append("relation = greater than")
            L.append("quantity = 0")
            L.append("realtime_schedule = 0")
            L.append("is_visible = false")
            th = c.get("throttle") or ({"fields": notable_fields(s), "period": "86400s" if c.get("window", "24h") == "24h" else "3600s"} if s.shape == "risk_threshold" else {})
            if th.get("fields"):
                L.append("alert.suppress = true")
                L.append("alert.suppress.fields = " + ",".join(th["fields"]))
                L.append(f"alert.suppress.period = {th.get('period', '3600s')}")
            L.append("search = " + flatten_spl(spl_for(s)))
            L.append("")
        return L

    def _macros(self, path: Path, avs: list[AnalyticView], svs: list) -> Path:
        L = ["# Generated by mitremap. Per-analytic tuning: one filter macro each, plus analytic-specific tunables",
             "# bound to ATT&CK mutable elements. Shared macros and lookups live in TA-mitre-attack-datacomponents.", ""]
        for v in avs:
            for stanza, definition, desc in tunable_macros(v):
                L += [f"[{stanza}]", f"definition = {definition}", f"description = {desc}", "iseval = 0", ""]
        from ..health import filter_macros
        for stanza, definition, desc in filter_macros():
            L += [f"[{stanza}]", f"definition = {definition}", f"description = {desc}", "iseval = 0", ""]
        from ..strategies import strategy_macros
        for sv in svs:
            for stanza, definition, desc in strategy_macros(sv):
                L += [f"[{stanza}]", f"definition = {definition}", f"description = {desc}", "iseval = 0", ""]
        path.write_text("\n".join(L), encoding="utf-8")
        return path

    def _transforms(self, path: Path, lookups: Path, avs: list[AnalyticView]) -> Path:
        L = ["# Generated by mitremap. Lookups written by baseline and supporting searches.", ""]
        from ..health import support_searches
        for sp in support_searches():
            L += [f"[{sp.lookup}]", f"filename = {sp.lookup}.csv", "case_sensitive_match = false", ""]
            p = lookups / f"{sp.lookup}.csv"
            if not p.exists():
                with p.open("w", newline="", encoding="utf-8") as fh:
                    csv.writer(fh).writerow(sp.fields)
        for v in avs:
            for b in v.curated.get("baselines") or []:
                name, fields = b["lookup"], b["fields"]
                L += [f"[{name}]", f"filename = {name}.csv", "case_sensitive_match = false", ""]
                p = lookups / f"{name}.csv"
                if not p.exists():   # header only; the baseline search fills it and a rebuild never overwrites it
                    with p.open("w", newline="", encoding="utf-8") as fh:
                        csv.writer(fh).writerow(fields)
        path.write_text("\n".join(L), encoding="utf-8")
        return path

    def _app_conf(self, path: Path, m: AttackModel) -> Path:
        path.write_text(
            "[install]\nis_configured = 1\nstate = enabled\n\n"
            "[ui]\nis_visible = 0\nlabel = MITRE ATT&CK Detections\n\n"
            f"[launcher]\nauthor = mitremap\ndescription = ATT&CK v{m.version} analytics as Enterprise Security detections\nversion = 0.2.0\n\n"
            f"[package]\nid = {APP}\ncheck_for_updates = 0\n", encoding="utf-8")
        return path

    def _readme(self, path: Path, m: AttackModel, avs: list[AnalyticView], svs: list) -> Path:
        from collections import Counter
        c = Counter(v.content_type for v in avs)
        seq = sum(1 for s in svs if s.shape == "sequence")
        rbt = sum(1 for s in svs if s.shape == "risk_threshold" and s.kind == "strategy")
        corr = sum(1 for s in svs if s.kind == "correlation")
        nb = sum(len(v.curated.get("baselines") or []) for v in avs)
        path.write_text(f"""# {APP}

ATT&CK v{m.version} analytics implemented as Splunk Enterprise Security 8 detections.
Requires `TA-mitre-attack-datacomponents` (eventtypes, macros, lookups) and Splunk_SA_CIM (ships with ES).

| Content type | Count | Adaptive response |
|---|---|---|
| TTP | {c['ttp']} | finding (notable) + risk |
| Anomaly | {c['anomaly']} | risk only (intermediate finding) |
| Hunting | {c['hunting']} | none; run on demand or schedule for a dashboard |
| Baselines | {nb} | write a lookup that an analytic reads |
| Strategy sequences | {seq} | finding + risk; raw-event chains joined on a key |
| Strategy risk rules | {rbt} | finding only; over the Risk data model, scoped to one strategy |
| Cross-strategy risk correlations | {corr} | finding only; over the Risk data model |

## Enabling

1. Every detection ships `disabled = true`. Enable from ES > Content Management, or set `disabled = false` in `local/savedsearches.conf`.
2. Before enabling one, run its search over 7 days, then add exclusions to its `mitre_anXXXX_filter` macro or the shared allowlist lookups. Do not edit the search.
3. Analytics that read a baseline lookup need the baseline enabled first and one full run.
4. Detections on data models use `mitre_summariesonly`; set it to `summariesonly=true` once the models are accelerated.

## Risk-based rules depend on asset and identity correlation

Endpoint analytics raise risk on host names (`dest` from Sysmon `Computer`), network analytics on IP addresses (`src` from Corelight and Palo Alto). The risk rules group by `risk_object`, so a host and its IP only meet if ES Asset and Identity management maps them (an asset lookup carrying both `ip` and `nt_host`/`dns`). Without that, cross-feed correlation silently fragments.

## Annotations

`action.correlationsearch.annotations` carries `mitre_attack` (technique), `mitre_det`, `mitre_an`, `mitre_dc` and `attack_version`, so risk events and findings can be grouped by any layer of the ATT&CK detection model.
""", encoding="utf-8")
        return path
